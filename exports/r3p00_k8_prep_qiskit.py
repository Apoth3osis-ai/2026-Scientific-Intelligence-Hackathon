from math import pi
from qiskit import QuantumCircuit
circuit = QuantumCircuit(2, 2)
circuit.sdg(0)
circuit.h(0)
circuit.p((1 * 1 * pi / 128), 0)
circuit.p((1 * 1 * pi / 64), 0)
circuit.p((1 * 1 * pi / 32), 0)
circuit.t(0)
circuit.s(0)
circuit.h(0)
circuit.s(0)
circuit.sdg(1)
circuit.h(1)
circuit.p((1 * 1 * pi / 128), 1)
circuit.t(1)
circuit.s(1)
circuit.z(1)
circuit.h(1)
circuit.s(1)
circuit.cx(0, 1)
circuit.sdg(1)
circuit.h(1)
circuit.p((1 * 1 * pi / 64), 1)
circuit.p((1 * 1 * pi / 8), 1)
circuit.s(1)
circuit.z(1)
circuit.h(1)
circuit.s(1)
circuit.cx(0, 1)
circuit.measure(0, 0)
circuit.measure(1, 1)
